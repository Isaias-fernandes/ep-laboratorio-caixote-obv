const assert = require('node:assert/strict');
const x = require('./structure-volume-lab.js');
assert.deepEqual(x.obv([{c:1,v:2},{c:2,v:3},{c:1,v:4},{c:1,v:8}]), [0,3,-1,-1]);
const candles = Array.from({length:100}, (_,i) => ({t:i*900000,o:100,c:100,h:101,l:99,v:100}));
assert.equal(x.rsi(candles), 50);
assert.equal(x.evaluate(candles,'15m',90000000).rows.length, 0);
assert.equal(x.evaluate(candles,'15m',89100000).candles, 99);
assert.throws(() => x.evaluate(candles,'1h',1e12), /intervalo/);
assert.throws(() => x.evaluate(candles,'1d'), /Selecione/);
const b = candles.slice(0,50).map((c,i) => ({...c,c:100+(i%2)*.1}));
b[49] = {...b[49],o:100,c:101.2,h:101.3,v:400};
assert.equal(x.detect(b,'15m').length, 1);
assert.equal(x.detect(b,'5m').length, 0);
const future = b.concat(candles.slice(50).map(c => ({...c,o:102,c:102,h:103,l:101})));
const row = x.evaluate(future,'15m',1e12).rows[0];
assert.equal(row.entry,102);
assert.equal(row.bars,48);
assert.equal(row.status,'AVALIADO');
future[99].h=1000;
assert.equal(x.evaluate(future,'15m',1e12).rows[0].mfe,row.mfe);
assert.equal(x.evaluate(future.slice(0,60),'15m',1e12).rows[0].status,'PARCIAL');
assert.equal(x.reversal({o:101,c:102,h:102.2,l:98},{o:102,c:101}),true);
console.log('14 assertions passed');
